  let current = localStorage.getItem(LANG_KEY) || 'th';
  if (!DICT[current]) current = 'th';

  function t(key, fallback) {
    const table = DICT[current] || DICT.th;
    if (Object.prototype.hasOwnProperty.call(table, key)) return table[key];
    if (Object.prototype.hasOwnProperty.call(DICT.th, key)) return DICT.th[key];
    return fallback !== undefined ? fallback : key;
  }

  function getLang() { return current; }

  function setLang(lang) {
    if (!DICT[lang]) return;
    current = lang;
    localStorage.setItem(LANG_KEY, lang);
    document.documentElement.lang = lang;
    apply();
    document.dispatchEvent(new CustomEvent('langchange', { detail: { lang } }));
  }

  function toggle() { setLang(current === 'th' ? 'en' : 'th'); }

  /* แทนข้อความให้ทุก element ที่มี data-i18n / data-i18n-ph / data-i18n-title */
  function apply(root) {
    const scope = root || document;
    scope.querySelectorAll('[data-i18n]').forEach(el => {
      el.textContent = t(el.getAttribute('data-i18n'));
    });
    scope.querySelectorAll('[data-i18n-html]').forEach(el => {
      el.innerHTML = t(el.getAttribute('data-i18n-html'));
    });
    scope.querySelectorAll('[data-i18n-ph]').forEach(el => {
      el.setAttribute('placeholder', t(el.getAttribute('data-i18n-ph')));
    });
    scope.querySelectorAll('[data-i18n-title]').forEach(el => {
      el.setAttribute('title', t(el.getAttribute('data-i18n-title')));
    });
    scope.querySelectorAll('[data-i18n-aria]').forEach(el => {
      el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria')));
    });
    document.documentElement.lang = current;
  }

  global.I18N = { t, apply, setLang, getLang, toggle, DICT };
